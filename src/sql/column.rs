// BoolOps — logical AND / OR
// ═══════════════════════════════════════════════════════════════════════════

/// Logical AND / OR for `Boolean` expressions. (NOT lives at the module
/// level as the free function [`crate::sql::not`].)
pub trait BoolOps: Expr<SqlType = Boolean> + Sized {
    /// `self AND rhs`.
    fn and<R: Expr<SqlType = Boolean>>(self, rhs: R) -> And<Self, R> {
        And {
            left: self,
            right: rhs,
        }
    }
    /// `self OR rhs`.
    fn or<R: Expr<SqlType = Boolean>>(self, rhs: R) -> Or<Self, R> {
        Or {
            left: self,
            right: rhs,
        }
    }
}
impl<E> BoolOps for E where E: Expr<SqlType = Boolean> + Sized {}
