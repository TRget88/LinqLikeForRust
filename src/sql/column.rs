// TextOps — lexicographic ordering + LIKE
// ═══════════════════════════════════════════════════════════════════════════

/// Text-specific operators: lexicographic comparison and `LIKE`.
pub trait TextOps: Expr<SqlType = Text> + Sized {
    /// `self < rhs` — lexicographic.
    fn lt<R: Expr<SqlType = Text>>(self, rhs: R) -> Lt<Self, R> {
        Lt {
            left: self,
            right: rhs,
        }
    }
    /// `self <= rhs` — lexicographic.
    fn lte<R: Expr<SqlType = Text>>(self, rhs: R) -> LtEq<Self, R> {
        LtEq {
            left: self,
            right: rhs,
        }
    }
    /// `self > rhs` — lexicographic.
    fn gt<R: Expr<SqlType = Text>>(self, rhs: R) -> Gt<Self, R> {
        Gt {
            left: self,
            right: rhs,
        }
    }
    /// `self >= rhs` — lexicographic.
    fn gte<R: Expr<SqlType = Text>>(self, rhs: R) -> GtEq<Self, R> {
        GtEq {
            left: self,
            right: rhs,
        }
    }
    /// `self LIKE pattern` — SQL `%`/`_` glob match.
    fn like<R: Expr<SqlType = Text>>(self, pattern: R) -> Like<Self, R> {
        Like {
            left: self,
            right: pattern,
        }
    }
}
impl<E> TextOps for E where E: Expr<SqlType = Text> + Sized {}

